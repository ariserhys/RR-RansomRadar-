"""RansomRadar dashboard (Streamlit) - a read-only view over the SQLite store.

Run with:  streamlit run app.py
"""
import json
import os
import time

import numpy as np
import pandas as pd
import streamlit as st

import db
import features
import model
from config import CANARY_DIR, MODEL_PATH, RESULTS_CSV, SANDBOX

st.set_page_config(page_title="RansomRadar", page_icon="🛡️", layout="wide")
db.init_db()

SEVERITY_TAG = {"CRITICAL": "🔴 CRITICAL", "HIGH": "🟠 HIGH", "MEDIUM": "🟡 MEDIUM"}

st.title("🛡️ RansomRadar — Explainable Ransomware Early Warning")
st.caption("Defensive prototype · all activity is generated by a benign simulator "
           "inside the sandbox folder · detection is passive (flags in a local database).")

# ------------------------------------------------------------------ sidebar
with st.sidebar:
    st.header("Control panel")
    auto = st.checkbox("Auto-refresh (3 s)", value=True, key="auto_refresh")

    bundle = model.load_bundle()
    st.write("**Detection mode:**",
             "Rules + ML (model trained)"
             if bundle else "Rules only — run `python model.py train` to enable ML")

    n_events, n_alerts = db.count("events"), db.count("alerts")
    cdir = SANDBOX / CANARY_DIR
    canaries = sorted(cdir.glob("*canary*")) if cdir.exists() else []
    st.write("**Canary decoys:**",
             f"{len(canaries)} in place" if canaries else "none yet — start the collector")

    if st.button("🗑️ Clear events & alerts (keeps sandbox files)"):
        db.init_db(reset=True)
        st.rerun()

    alerts_all = db.all_alerts_df()
    st.download_button("⬇️ Export alerts (CSV)",
                       alerts_all.to_csv(index=False).encode("utf-8"),
                       "ransomradar_alerts.csv", "text/csv",
                       disabled=alerts_all.empty)
    if RESULTS_CSV.exists():
        st.download_button("⬇️ Export experiment results",
                           RESULTS_CSV.read_bytes(), "experiment_results.csv")

    with st.expander("How to run the demo"):
        st.code("python simulator.py --reset       # once, collector paused\n"
                "python collector.py                # terminal 1\n"
                "python simulator.py --mode benign  # terminal 2 (train)\n"
                "python model.py train              # after the benign run\n"
                "python simulator.py --mode attack  # watch the dashboard react",
                language="bash")

# ------------------------------------------------------------------ headline
c1, c2, c3, c4 = st.columns(4)
c1.metric("Events logged", n_events)
c2.metric("Alerts raised", n_alerts)
last_ts = alerts_all["ts"].max() if not alerts_all.empty else None
c3.metric("Last alert",
          time.strftime("%H:%M:%S", time.localtime(last_ts)) if last_ts else "—")
c4.metric("Model", "Trained" if bundle else "Rules only")

# ------------------------------------------------------------------ alerts
st.subheader("⚠️ Alerts (newest first)")
if alerts_all.empty:
    st.info("No alerts yet. Run `python simulator.py --mode attack` while the "
            "collector is running — or `python demo.py` for the scripted demo.")
else:
    show = alerts_all.copy()
    show["time"] = show["ts"].map(lambda t: time.strftime("%H:%M:%S", time.localtime(t)))
    show["severity"] = show["severity"].map(lambda s: SEVERITY_TAG.get(s, s))
    st.dataframe(show[["time", "source", "severity", "rule_name", "ml_score",
                       "explanation"]], height=260)

    top = show.head(50)
    labels = [f"#{int(r.id)} · {r.rule_name} · {r.time}" for r in top.itertuples()]
    choice = st.selectbox("Inspect an alert (the explainability panel)", labels)
    row = top.iloc[labels.index(choice)]
    with st.expander("Alert evidence", expanded=True):
        st.markdown(
            f"**{row['severity']}** · source `{row['source']}` · "
            f"ML score **{row['ml_score']:.0f}/100** · "
            f"session `{row['session_id']}`")
        st.write(row["explanation"])
        if row["features_json"]:
            st.dataframe(pd.DataFrame([json.loads(row["features_json"])]))

# ------------------------------------------------------------------ timeline
st.subheader("📈 Event activity per 10 s window")
events = db.all_events()
wins, _ = features.windows_from_events(events)
if wins.empty:
    st.info("No events yet — start the collector and the simulator.")
else:
    alert_ws = set(alerts_all["window_start"].dropna()) if not alerts_all.empty else set()
    chart = pd.DataFrame(
        {"events/min": wins["event_rate"].values,
         "alerted window": [r["event_rate"] if r["window_start"] in alert_ws
                            else np.nan for _, r in wins.iterrows()]},
        index=pd.to_datetime(wins["window_start"], unit="s"))
    st.bar_chart(chart, height=240)

# ------------------------------------------------------------------ live feed
st.subheader("👀 Live event feed (latest 12)")
ev = db.recent_events_df(12)
if ev.empty:
    st.info("Waiting for events…")
else:
    ev["time"] = ev["ts"].map(lambda t: time.strftime("%H:%M:%S", time.localtime(t)))
    ev["file"] = ev["src_path"].map(lambda p: os.path.basename(p or "?"))
    ev["dest"] = ev["dest_path"].map(lambda p: os.path.basename(p) if p else "")
    st.dataframe(ev[["time", "event_type", "file", "dest"]], height=220)

if auto:
    time.sleep(3)
    st.rerun()
